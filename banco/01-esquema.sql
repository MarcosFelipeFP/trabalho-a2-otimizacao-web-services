-- Esquema da biblioteca: categorias, autores, livros, leitores e empréstimos.
--
-- No Supabase, rodado pelo psql com o usuário postgres do projeto, o mesmo que a API usa (ver
-- "Como executar" no README). No PostgreSQL local (perfil banco-local do Docker Compose),
-- executado automaticamente pelo contêiner do banco na primeira subida.

-- Estatísticas por comando SQL, usadas na análise dos testes de carga, e carga das tabelas na
-- memória do banco antes das medições (rota /api/laboratorio/banco/aquecer). O Supabase guarda as
-- extensões no schema extensions (o pg_stat_statements já vem instalado); o PostgreSQL local não
-- tem esse schema, e elas ficam no public.
DO $$
BEGIN
    IF to_regnamespace('extensions') IS NOT NULL THEN
        CREATE EXTENSION IF NOT EXISTS pg_stat_statements WITH SCHEMA extensions;
        CREATE EXTENSION IF NOT EXISTS pg_prewarm WITH SCHEMA extensions;
    ELSE
        CREATE EXTENSION IF NOT EXISTS pg_stat_statements;
        CREATE EXTENSION IF NOT EXISTS pg_prewarm;
    END IF;
END $$;

-- As tabelas têm muitas colunas, como os cadastros de uma biblioteca real: a ficha catalográfica
-- de um livro e o cadastro de um leitor têm dezenas de campos. As listagens estudadas no item 2
-- usam poucos deles (o título do livro e o nome do leitor), mas o ORM traz todas as colunas sempre
-- que carrega uma entidade inteira. É esse volume de dados desnecessários que as consultas
-- otimizadas evitam (seção 4 do README).

CREATE TABLE categoria (
    id   smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(60) NOT NULL UNIQUE
);

CREATE TABLE autor (
    id              integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            varchar(120) NOT NULL,
    nacionalidade   varchar(40)  NOT NULL,
    biografia       text,
    ano_nascimento  smallint,
    ano_falecimento smallint,
    cidade_natal    varchar(60),
    site            varchar(120),
    premios         varchar(200)
);

CREATE TABLE livro (
    id                       integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                   varchar(200) NOT NULL,
    isbn                     char(13)     NOT NULL UNIQUE,
    editora                  varchar(80)  NOT NULL,
    ano_publicacao           smallint     NOT NULL,
    paginas                  smallint     NOT NULL,
    sinopse                  text         NOT NULL,
    autor_id                 integer      NOT NULL REFERENCES autor (id),
    categoria_id             smallint     NOT NULL REFERENCES categoria (id),
    total_exemplares         smallint     NOT NULL CHECK (total_exemplares > 0),
    exemplares_disponiveis   smallint     NOT NULL,
    atualizado_em            timestamp    NOT NULL DEFAULT localtimestamp,
    -- ficha catalográfica
    subtitulo                varchar(200),
    edicao                   smallint     NOT NULL DEFAULT 1,
    ano_edicao               smallint,
    local_publicacao         varchar(60),
    idioma                   varchar(20)  NOT NULL DEFAULT 'Português',
    idioma_original          varchar(20),
    tradutor                 varchar(120),
    ilustrador               varchar(120),
    colecao                  varchar(80),
    volume                   smallint,
    formato                  varchar(20),
    largura_cm               numeric(4,1),
    altura_cm                numeric(4,1),
    espessura_cm             numeric(4,1),
    peso_g                   smallint,
    isbn10                   char(10),
    cdd                      varchar(12),
    cutter                   varchar(8),
    assuntos                 varchar(300),
    publico_alvo             varchar(30),
    classificacao_indicativa varchar(10),
    sumario                  text,
    notas                    text,
    url_capa                 varchar(200),
    -- acervo
    codigo_barras            char(13),
    localizacao              varchar(30),
    estado_conservacao       varchar(20),
    origem                   varchar(20),
    data_aquisicao           date,
    preco_aquisicao          numeric(8,2),
    fornecedor               varchar(80),
    nota_fiscal              varchar(20),
    avaliacao_media          numeric(3,2),
    total_avaliacoes         integer      NOT NULL DEFAULT 0,
    cadastrado_em            timestamp    NOT NULL DEFAULT localtimestamp,
    CHECK (exemplares_disponiveis BETWEEN 0 AND total_exemplares)
);

CREATE TABLE leitor (
    id                   integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                 varchar(120) NOT NULL,
    email                varchar(160) NOT NULL UNIQUE,
    cadastrado_em        date         NOT NULL,
    numero_carteirinha   char(10),
    data_nascimento      date,
    tipo                 varchar(20),
    matricula            varchar(20),
    curso                varchar(80),
    unidade              varchar(40),
    logradouro           varchar(120),
    numero               varchar(10),
    complemento          varchar(60),
    bairro               varchar(60),
    cidade               varchar(60),
    uf                   char(2),
    cep                  char(8),
    validade_carteirinha date,
    situacao             varchar(20)  NOT NULL DEFAULT 'Ativo',
    limite_emprestimos   smallint     NOT NULL DEFAULT 3,
    multas_pendentes     numeric(8,2) NOT NULL DEFAULT 0,
    aceita_notificacoes  boolean      NOT NULL DEFAULT true,
    canal_preferido      varchar(20),
    categorias_favoritas varchar(200),
    observacoes          text,
    foto_url             varchar(200),
    ultimo_acesso        timestamp,
    atualizado_em        timestamp
);

CREATE TABLE emprestimo (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id        integer      NOT NULL REFERENCES livro (id),
    leitor_id       integer      NOT NULL REFERENCES leitor (id),
    data_emprestimo timestamp    NOT NULL,
    data_prevista   date         NOT NULL,
    data_devolucao  timestamp,
    canal           varchar(20)  NOT NULL DEFAULT 'Balcão',
    atendente       varchar(60),
    renovacoes      smallint     NOT NULL DEFAULT 0,
    data_renovacao  date,
    multa           numeric(8,2) NOT NULL DEFAULT 0,
    avaliacao       smallint     CHECK (avaliacao BETWEEN 1 AND 5),
    observacoes     varchar(200),
    registrado_em   timestamp    NOT NULL DEFAULT localtimestamp,
    CHECK (data_devolucao IS NULL OR data_devolucao >= data_emprestimo)
);

-- Os índices além das chaves primárias e únicas são criados depois da carga dos dados, em
-- 03-indices.sql.

-- No Supabase, o schema public também é servido pela API REST automática do projeto (Data API),
-- que qualquer um com a chave pública pode chamar. Com RLS ligado e nenhuma política, essa API não
-- lê nem altera nada. O dono das tabelas (o usuário postgres, que a nossa API usa) não é afetado
-- pelo RLS.
ALTER TABLE categoria ENABLE ROW LEVEL SECURITY;
ALTER TABLE autor ENABLE ROW LEVEL SECURITY;
ALTER TABLE livro ENABLE ROW LEVEL SECURITY;
ALTER TABLE leitor ENABLE ROW LEVEL SECURITY;
ALTER TABLE emprestimo ENABLE ROW LEVEL SECURITY;
