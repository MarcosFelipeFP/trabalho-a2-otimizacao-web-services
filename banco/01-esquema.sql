-- Esquema da biblioteca: categorias, autores, livros, leitores e empréstimos.
-- Executado automaticamente pelo contêiner do PostgreSQL na primeira subida.

-- Estatísticas por comando SQL, usadas na análise dos testes de carga.
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;
-- Carga das tabelas na memória do banco antes das medições (rota /api/laboratorio/banco/aquecer).
CREATE EXTENSION IF NOT EXISTS pg_prewarm;

CREATE TABLE categoria (
    id   smallint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(60) NOT NULL UNIQUE
);

CREATE TABLE autor (
    id            integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          varchar(120) NOT NULL,
    nacionalidade varchar(40)  NOT NULL
);

CREATE TABLE livro (
    id                     integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                 varchar(200) NOT NULL,
    isbn                   char(13)     NOT NULL UNIQUE,
    editora                varchar(80)  NOT NULL,
    ano_publicacao         smallint     NOT NULL,
    paginas                smallint     NOT NULL,
    sinopse                text         NOT NULL,
    autor_id               integer      NOT NULL REFERENCES autor (id),
    categoria_id           smallint     NOT NULL REFERENCES categoria (id),
    total_exemplares       smallint     NOT NULL CHECK (total_exemplares > 0),
    exemplares_disponiveis smallint     NOT NULL,
    atualizado_em          timestamp    NOT NULL DEFAULT localtimestamp,
    CHECK (exemplares_disponiveis BETWEEN 0 AND total_exemplares)
);

CREATE TABLE leitor (
    id            integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          varchar(120) NOT NULL,
    email         varchar(160) NOT NULL UNIQUE,
    cadastrado_em date         NOT NULL
);

CREATE TABLE emprestimo (
    id              bigint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    livro_id        integer   NOT NULL REFERENCES livro (id),
    leitor_id       integer   NOT NULL REFERENCES leitor (id),
    data_emprestimo timestamp NOT NULL,
    data_prevista   date      NOT NULL,
    data_devolucao  timestamp,
    CHECK (data_devolucao IS NULL OR data_devolucao >= data_emprestimo)
);

